import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import { openHarness } from './refactor-20261008-harness.mjs';
const h=await openHarness();
const page=h.page;
const output=process.env.TCPLUS_OUTLOOK_SCREENSHOTS;
const shot=async name=>{if(output){fs.mkdirSync(output,{recursive:true});await page.screenshot({path:path.join(output,name+'.png')});}};
try {
  await h.boot();
  const calendar=page.locator('[data-view="calendar"]');
  const settings=page.locator('[data-settings-dialog]');
  const taskDialog=calendar.locator('[data-task-dialog]');
  for(const enabled of [true,false]) {
    await calendar.locator('[data-settings-btn]').click();
    await settings.locator('[data-settings-tab="outlook"]').click();
    await settings.locator('[name="outlookWriteDefault"]').setChecked(enabled);
    if(enabled) await shot('outlook-default-settings');
    await settings.locator('[data-settings-save]').click();
    await settings.waitFor({state:'hidden'});
    assert.equal(h.state().settings.outlookWriteDefault,enabled);
    await calendar.locator('[data-settings-btn]').click();
    await settings.locator('[data-settings-tab="outlook"]').click();
    assert.equal(await settings.locator('[name="outlookWriteDefault"]').isChecked(),enabled);
    await settings.locator('[data-settings-cancel]').click();
    await calendar.locator('[data-new-task]').click();
    const toggle=taskDialog.locator('[name="outlookEnabled"]');
    assert.equal(await toggle.isChecked(),enabled);
    await toggle.focus(); await page.keyboard.press("Space");
    await taskDialog.locator('[name="title"]').fill('Outlook choice '+enabled);
    await taskDialog.locator('[data-save]').click();
    await taskDialog.waitFor({state:'hidden'});
    assert.equal(h.state().tasks.find(t=>t.title==='Outlook choice '+enabled).outlookEnabled,!enabled);
  }
  await page.locator('nav.nav [data-nav-target="tasks"]').click();
  const tasks=page.locator('[data-view="tasks"]');
  const edit=tasks.locator('[data-task-dialog]');
  const saved=h.state().tasks.find(t=>t.title==='Outlook choice false');
  await tasks.locator(`[data-task-id="${saved.id}"] [data-edit]`).click();
  assert.equal(await edit.locator('[name="outlookEnabled"]').isEnabled(),true);
  assert.equal(await edit.locator('[name="outlookEnabled"]').isChecked(),true);
  await shot('task-outlook-selection');
  await edit.locator('[name="outlookEnabled"]').locator("..").click();
  await edit.locator('[data-cancel]').click();
  assert.equal(h.state().tasks.find(t=>t.id===saved.id).outlookEnabled,true,'cancel preserves selection');
  await tasks.locator(`[data-task-id="${saved.id}"] [data-edit]`).click();
  await edit.locator('[name="outlookEnabled"]').locator("..").click();
  await edit.locator('[data-save]').click();
  await edit.waitFor({state:'hidden'});
  assert.equal(h.state().tasks.find(t=>t.id===saved.id).outlookEnabled,false);
  await tasks.locator(`[data-task-id="${saved.id}"] [data-edit]`).click();
  assert.equal(await edit.locator('[name="outlookEnabled"]').isChecked(),false);
  await page.setViewportSize({width:800,height:900});
  await page.evaluate(()=>document.documentElement.dataset.theme='dark');
  await shot('task-outlook-selection-dark');
  const box=await edit.locator('[name="outlookEnabled"]').boundingBox();
  assert.ok(box&&box.x>=0&&box.y>=0&&box.y+box.height<=900,'switch remains reachable');
  assert.deepEqual(h.pageErrors,[]);
  console.log('PASS: Outlook defaults save/reopen, new overrides, existing selection, cancel/save, narrow dark UI (synthetic API)');
} finally {await h.close();}
