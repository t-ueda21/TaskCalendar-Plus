import assert from 'node:assert/strict';
import {openHarness} from './refactor-20261008-harness.mjs';
const h=await openHarness();const p=h.page;
const calendar=(entry,store,label)=>({id:'outlook-folder:'+JSON.stringify({entryId:entry,storeId:store,label}),label});
const choices=[calendar('folder-a'.repeat(30),'store-a'.repeat(30),'Account A / Calendar'),calendar('folder-b'.repeat(30),'store-b'.repeat(30),'Account B / Calendar')];
let requestCount=0, hold=null, failure=false;
await p.route('**/api/outlook/calendars',async route=>{requestCount++;if(hold)await hold;if(failure)return route.fulfill({status:503,json:{error:'Outlook unavailable'}});return route.fulfill({json:{calendars:choices,warnings:[]}});});
try {
 await h.boot();await p.locator('[data-view="calendar"] [data-settings-btn]').click();
 const settings=p.locator('[data-settings-dialog]');
 await settings.locator('[data-settings-tab="outlook"]').click();
 const source=settings.locator('[data-outlook-calendar-picker="source"]');
 const target=settings.locator('[data-outlook-calendar-picker="target"]');
 await source.locator('select').waitFor({timeout:1500});
 await p.waitForFunction(()=>document.querySelector('[data-outlook-calendar-picker="source"] select')?.options.length>=4);
 assert.equal(requestCount,1);
 await source.locator('select').selectOption(choices[0].id);
 await target.locator('select').selectOption(choices[1].id);
 await settings.locator('[data-settings-save]').click();await settings.waitFor({state:'hidden'});
 assert.equal(h.state().settings.outlookSyncCalendarName,choices[0].id);
 assert.equal(h.state().settings.outlookWriteCalendarName,choices[1].id,'long IDs must survive Store normalization');
 await p.locator('[data-view="calendar"] [data-settings-btn]').click();await settings.locator('[data-settings-tab="outlook"]').click();
 assert.equal(await source.locator('select').inputValue(),choices[0].id);
 assert.equal(await target.locator('select').inputValue(),choices[1].id);
 let release;hold=new Promise(resolve=>release=resolve);
 await source.locator('[data-calendar-refresh]').click();
 await target.locator('select').selectOption('Calendar');
 release();hold=null;
 await p.waitForFunction(()=>!document.querySelector('[data-calendar-refresh]').disabled);
 assert.equal(await target.locator('select').inputValue(),'Calendar','late response preserves latest choice');
 failure=true;await source.locator('[data-calendar-refresh]').click();
 await p.waitForFunction(()=>!document.querySelector('[data-calendar-refresh]').disabled);
 assert.equal(await source.locator('select').inputValue(),choices[0].id);
 assert.match(await source.locator('[data-calendar-status]').innerText(),/Outlook unavailable/);
 await target.locator('select').selectOption('__manual_calendar__');
 await target.locator('input').fill('My custom calendar');
 await settings.locator('[data-settings-save]').click();await settings.waitFor({state:'hidden'});
 assert.equal(h.state().settings.outlookWriteCalendarName,'My custom calendar');
 assert.deepEqual(h.pageErrors,[]);
 console.log('PASS: independent Outlook calendars, duplicate labels, stable long IDs, save/reopen, refresh race, error retention and manual entry');
}finally{await h.close();}
