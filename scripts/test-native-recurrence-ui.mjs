import assert from 'node:assert/strict';
import {openHarness} from './refactor-20261008-harness.mjs';
const h=await openHarness();
try{
  await h.boot();
  const calendar=h.page.locator('[data-view="calendar"]'),dialog=calendar.locator('[data-task-dialog]');
  await calendar.locator('[data-new-task]').click();
  await dialog.locator('[name="title"]').fill('Native weekly');
  await dialog.locator('[name="date"]').fill('2026-10-05');
  await dialog.locator('[name="endDate"]').fill('2026-10-05');
  await dialog.locator('[name="startTime"]').fill('09:00');
  await dialog.locator('[name="endTime"]').fill('10:00');
  await dialog.locator('[data-native-recurrence] summary').click();
  await dialog.locator('[name="nativeEnabled"]').check();
  await dialog.locator('[name="nativeType"]').selectOption('1');
  await dialog.locator('[name="nativeStart"]').fill('2026-10-05');
  for(const input of await dialog.locator('[name="nativeWeekday"]').all())await input.uncheck();
  await dialog.locator('[name="nativeWeekday"][value="2"]').check();
  await dialog.locator('[name="nativeWeekday"][value="8"]').check();
  await dialog.locator('[name="nativeEndMode"]').selectOption('count');
  await dialog.locator('[name="nativeCount"]').fill('3');
  await dialog.locator('[data-save]').click();
  await dialog.waitFor({state:'hidden'});
  const rows=h.state().tasks.filter(row=>row.title==='Native weekly');
  assert.deepEqual(rows.map(row=>row.date),['2026-10-05','2026-10-07','2026-10-12']);
  assert.equal(rows[0].recurrence.native.dayOfWeekMask,10);
  assert.equal(rows[0].recurrence.template.date,'2026-10-05');
  await h.page.evaluate(async id=>{
    const S=await import('/src/store.js'),U=await import('/src/ui-utils.js');
    const row=S.getAllTasks().find(row=>row.id===id);
    await S.updateTask(id,{date:'2026-10-06',endDate:'2026-10-06',startTime:'11:00',endTime:'12:00'});
    const moved=S.getAllTasks().find(row=>row.id===id);
    U.openEditDialog(document.querySelector('[data-view="calendar"] [data-task-dialog]'),moved,S.getAllTags());
  },rows[0].id);
  const moved=h.state().tasks.find(row=>row.id===rows[0].id);
  assert.equal(moved.recurrence.occurrenceDate,'2026-10-05');
  assert.equal(moved.recurrence.template.startTime,'09:00');
  await dialog.locator('[name="nativeEnabled"]').uncheck();
  const requests=h.apiLog.length;
  await dialog.locator('[data-save]').click();
  const scope=h.page.locator('[data-save-scope]');
  await scope.waitFor();
  assert.equal(await scope.locator('[value=single]').count(),0,'rule changes exclude single occurrence');
  await scope.locator('[value=series]').check();
  await scope.locator('[data-scope-confirm]').click();
  const confirmation=h.page.locator('[data-app-dialog]');
  await confirmation.waitFor({state:'visible'});
  assert.match(await confirmation.locator('[data-app-dialog-message]').textContent(),/3/,'removal confirmation states affected local count');
  await confirmation.locator('[data-app-dialog-cancel]').click();
  assert.equal(await dialog.isVisible(),true);
  assert.equal(h.apiLog.slice(requests).some(row=>row.route.startsWith('/api/outlook/series/')),false,'cancel does not queue a removal');
  assert.equal(h.state().tasks.filter(row=>row.title==='Native weekly').length,3);
  await dialog.locator('[data-cancel]').click();
  assert.deepEqual(h.pageErrors,[]);
  console.log('PASS native weekly form, stable master template, moved occurrence identity and removal cancellation');
}finally{await h.close();}
